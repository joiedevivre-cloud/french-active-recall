-- Migration: 0016_vocabulary_dictionary
-- Purpose  : Turns the per-lemma vocabulary feature (0014) into a long-term
--            accumulating personal dictionary: a lemma keeps ALL of its
--            senses/usages (not one guessed meaning), dictionary-seeded
--            usages are distinguished from ones actually learned from a
--            saved sentence, FSRS review is tracked per USAGE (not just
--            per expression), and Korean phonetic transliteration is
--            replaced with real IPA everywhere.
--
-- Purely additive to every existing table: new nullable/defaulted columns
-- and one constraint-widening change (expression_id becomes nullable on
-- review_states/review_attempts, paired with a new lemma_usage_id so FSRS
-- can be polymorphic over "a card is about one expression OR one usage" --
-- no new, duplicate SRS table). No existing row's meaning changes, no
-- table or column is dropped.
-- =============================================================================

