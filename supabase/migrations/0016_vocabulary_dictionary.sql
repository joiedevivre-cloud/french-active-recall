  add constraint review_attempts_exactly_one_target
  check ((expression_id is not null) <> (lemma_usage_id is not null));

create index idx_review_attempts_lemma_usage_id
  on public.review_attempts (lemma_usage_id)
  where lemma_usage_id is not null;

comment on column public.review_states.lemma_usage_id is 'Set instead of expression_id for a usage-level FSRS card ("have I learned this sense of this word", not "have I learned this one sentence"). Created when a usage is first linked to a real sentence, or manually via the vocabulary screen''s "학습하기" button.';

-- -----------------------------------------------------------------------------
-- confirm_review_grade: generalized to accept EITHER p_expression_id OR
-- p_lemma_usage_id (exactly one). Dropped and recreated (not just
-- replaced) because the two id params move to the end of the parameter
-- list with defaults -- Postgres requires every parameter after the first
-- one with a default to also have a default, and the original
-- p_expression_id sat in the middle of several non-default parameters.
-- Every existing call site (TodayReview.tsx, WritingCardShell.tsx) calls
-- this via Supabase's named-parameter RPC convention, so reordering
-- parameters in the definition has NO effect on them -- they keep passing
-- p_expression_id by name exactly as before, p_lemma_usage_id simply
-- defaults to null (unchanged behavior).
-- -----------------------------------------------------------------------------
drop function if exists public.confirm_review_grade(uuid, uuid, uuid, text, text, text, jsonb, uuid, text, int, boolean, text, jsonb, text[]);

create function public.confirm_review_grade(
  p_client_id uuid,
  p_review_state_id uuid,
  p_rating text,
  p_attempt_type text,
  p_mode text,
  p_new_review_state jsonb,
  p_exercise_id uuid default null,
  p_response_text text default null,
  p_response_time_ms int default null,
  p_hint_used boolean default false,
  p_ai_suggested_rating text default null,
  p_ai_feedback jsonb default null,
  p_grammar_tags text[] default '{}',
  p_expression_id uuid default null,
  p_lemma_usage_id uuid default null
) returns table (attempt_id uuid, already_applied boolean)
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_attempt_id uuid;
begin
  if (p_expression_id is null) = (p_lemma_usage_id is null) then
    raise exception 'exactly_one_of_expression_id_or_lemma_usage_id_required';
  end if;

  select id into v_attempt_id
  from public.review_attempts
  where user_id = v_user_id and client_id = p_client_id;

  if v_attempt_id is not null then
    return query select v_attempt_id, true;
    return;
  end if;

  update public.review_states set
    due_at               = (p_new_review_state ->> 'due_at')::timestamptz,
    stability            = (p_new_review_state ->> 'stability')::numeric,
    difficulty           = (p_new_review_state ->> 'difficulty')::numeric,
    elapsed_days         = (p_new_review_state ->> 'elapsed_days')::numeric,
    scheduled_days       = (p_new_review_state ->> 'scheduled_days')::numeric,
    reps                 = (p_new_review_state ->> 'reps')::int,
    lapses               = (p_new_review_state ->> 'lapses')::int,
    state                = p_new_review_state ->> 'state',
    last_reviewed_at     = (p_new_review_state ->> 'last_reviewed_at')::timestamptz,
    last_retrievability  = coalesce((p_new_review_state ->> 'last_retrievability')::numeric, last_retrievability),
    consecutive_correct  = case when p_rating = 'again' then 0 else consecutive_correct + 1 end
  where id = p_review_state_id and user_id = v_user_id;

  if not found then
    raise exception 'review_state_not_found_or_not_owned';
  end if;

  insert into public.review_attempts (
    user_id, expression_id, lemma_usage_id, attempt_type, mode, exercise_id, response_text,
    response_time_ms, hint_used, self_rating, ai_suggested_rating, ai_feedback,
    grammar_tags, client_id
  ) values (
    v_user_id, p_expression_id, p_lemma_usage_id, p_attempt_type, p_mode, p_exercise_id, p_response_text,
    p_response_time_ms, p_hint_used, p_rating, p_ai_suggested_rating, p_ai_feedback,
    p_grammar_tags, p_client_id
  ) returning id into v_attempt_id;

  return query select v_attempt_id, false;
end;
$$;

revoke execute on function public.confirm_review_grade(uuid, uuid, text, text, text, jsonb, uuid, text, int, boolean, text, jsonb, text[], uuid, uuid) from public, anon;
grant execute on function public.confirm_review_grade(uuid, uuid, text, text, text, jsonb, uuid, text, int, boolean, text, jsonb, text[], uuid, uuid) to authenticated;

